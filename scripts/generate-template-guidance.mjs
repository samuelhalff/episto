#!/usr/bin/env node
/**
 * Generates `shared/src/template-guidance/<locale>.ts` from the frontend landing
 * content.
 *
 * The AI guidance for a template used to travel on the wire beside the slug, so
 * a client could pair slug A's display copy with template B's guidance. The
 * server now rebuilds guidance from the validated slug alone, which means it
 * needs its own copy of the content — and that copy must be mechanically derived
 * rather than retyped, or the two will disagree in ways nobody notices.
 *
 * Re-run after editing landing content:
 *   node scripts/generate-template-guidance.mjs && (cd shared && npm run build)
 *
 * `frontend/tests/template-guidance-registry-drift.test.ts` fails if the
 * committed output no longer matches the landing content.
 */

import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

/**
 * The landing datasets are TypeScript modules with imports, so they are read
 * through tsx rather than parsed. Emitting JSON from a child process keeps this
 * script free of a bundler.
 */
function loadTs(file, exportName) {
  const script = `
    import { ${exportName} as value } from ${JSON.stringify(path.join(repoRoot, file))};
    process.stdout.write(JSON.stringify(value));
  `;
  return JSON.parse(
    execFileSync("npx", ["tsx", "--eval", script], {
      cwd: repoRoot,
      encoding: "utf8",
      maxBuffer: 32 * 1024 * 1024,
    }),
  );
}

/**
 * Which locales exist is the landing content's business, not this script's.
 * Hardcoding the list here would mean a fourth authored locale generates nothing
 * and silently falls back to German.
 */
const LANGUAGES = loadTs("frontend/src/lib/landing-routes.ts", "LANDING_LOCALES").map(
  (locale) => locale.slice(0, 2),
);

const loadPages = (language) =>
  loadTs(
    `frontend/src/lib/landing/${language}.ts`,
    `${language.toUpperCase()}_LANDING_PAGES`,
  );

/**
 * Emitted as one JSON object literal and handed to prettier afterwards, so the
 * committed file is byte-identical to what the pre-commit hook would produce —
 * otherwise the hook reformats it and every later regeneration shows a diff that
 * isn't a content change.
 */
function render(locale, entries) {
  return (
    `// GENERATED by scripts/generate-template-guidance.mjs — do not edit by hand.\n` +
    `// Source: frontend/src/lib/landing/${locale}.ts\n` +
    `import type { TemplateGuidanceEntry } from "./types.ts";\n\n` +
    `export const templateGuidance: Record<string, TemplateGuidanceEntry> = ` +
    `${JSON.stringify(Object.fromEntries(entries), null, 2)};\n`
  );
}

/**
 * Only the slugs that may seed a draft. The landing datasets also hold service
 * guides, which never reach the assistant, and shipping their copy to the model
 * would be dead weight at best.
 */
const draftSlugs = new Set(
  loadTs("shared/src/workspace-draft.ts", "DRAFT_TEMPLATE_SLUGS"),
);
const outDir = path.join(repoRoot, "shared/src/template-guidance");
mkdirSync(outDir, { recursive: true });

for (const locale of LANGUAGES) {
  const entries = loadPages(locale)
    .filter((page) => draftSlugs.has(page.slug))
    .map((page) => [
      page.slug,
      {
        checklist: page.checklist ?? [],
        // Flattened the same way the client used to, so the model sees exactly
        // the string it saw before this change.
        considerations: (page.notes ?? []).map((note) => `${note.title}: ${note.body}`),
      },
    ])
    .sort(([a], [b]) => a.localeCompare(b));

  writeFileSync(path.join(outDir, `${locale}.ts`), render(locale, entries), "utf8");
  console.log(`${locale}: ${entries.length} templates`);
}

// The registry map is generated too. Hand-maintaining the imports is the one
// place a newly authored locale would be quietly left out — it would resolve
// through the fallback instead, in the wrong language, with nothing failing.
writeFileSync(
  path.join(outDir, "registry.ts"),
  `// GENERATED by scripts/generate-template-guidance.mjs — do not edit by hand.\n` +
    LANGUAGES.map((l) => `import { templateGuidance as ${l} } from "./${l}.ts";\n`).join(
      "",
    ) +
    `import type { TemplateGuidanceEntry } from "./types.ts";\n\n` +
    `export const REGISTRY: Record<string, Record<string, TemplateGuidanceEntry>> = ` +
    `{ ${LANGUAGES.join(", ")} };\n`,
  "utf8",
);

execFileSync("npx", ["prettier", "--write", `${outDir}/*.ts`], {
  cwd: repoRoot,
  stdio: "ignore",
});
